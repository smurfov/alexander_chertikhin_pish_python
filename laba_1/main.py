# Задача №4
# Ввести целое число и определить, верно ли, что все его цифры расположены в порядке возрастания.
print("\nЗадача №4")
number = int(input("Введите ваше число: "))

if number < 0:
	number = abs(number)

is_increasing = True

while number > 0:
	a = number % 10
	number //= 10
	b = number % 10
	if b == 0: break
	if a < b:
		is_increasing = False
		break
	# print(a, b)

if is_increasing:
	print("Все цифры в числе расположены в порядке возрастания")
