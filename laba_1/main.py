# Задача №1
# Ввести натуральное число вывести квадраты и кубы всех чисел от 1 до этого числа. Число не превосходит 100. Формат входных данных: Одно целое число, не превосходящее 100 Формат результата: Для каждого из чисел от 1 до введенного числа напечатать квадрат числа и его куб.
print("Задача №1")
number = int(input("Введите ваше число: "))

def sum(number):
	for a in range(number+1):
		if a > 0:
			print("Число: ", a, "   Квадрат: ", a**2, "   Куб: ", a**3)


if number > 100:
	print("Ваше число больше 100. Переделывай.")
else:
	sum(number)

